/**
 * レシピのバリエーション提案プロンプト
 */
export function createVariationPrompt(originalRecipe: string): string {
  return `
以下の麹レシピのバリエーションを3つ提案してください。
元のレシピを基に、材料や調理法を少し変えたアレンジレシピを作成してください。

## 元のレシピ
${originalRecipe}

## 出力形式
各バリエーションをJSON配列形式で出力してください（同じ形式で3つ）。
`.trim();
}

