【前提思想】
- 麹調味料は「これ一つで味付けができる自然由来の調味料」
- 野菜と麹の旨味を凝縮し、大人から子どもまで満足できる味わい
- 料理が苦手な人でも失敗しにくく、味が決まりやすい
- 塩の代用品ではなく「旨味を軸に味を組み立てる調味料」

【基本特性】
- 塩分濃度は一般的な塩こうじ・コンソメ・中華だしの約40〜50%以下
- 塩分が低くても、麹と野菜の旨味により物足りなくなりにくい
- 加熱すると味のまとまりが増す（スープ・煮込みは煮込むほど奥深い味に）
- 砂糖のような甘さではなく、料理全体に深みを与える甘み

【調理ロジック】
- 味付けをするタイミングで使用（下味専用でも仕上げ専用でもない）
