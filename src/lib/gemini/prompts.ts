// Gemini API プロンプトテンプレート

export interface RecipeGenerationInput {
  kojiType: string; // 麹の種類（米麹、麦麹、豆麹など）
  difficulty?: string; // 難易度（かんたん、ふつう、むずかしい）
  additionalRequirements?: string; // その他の要望
}

export interface GeneratedRecipe {
  title: string;
  description: string;
  koji_type: string;
  difficulty: string;
  ingredients: Array<{
    name: string;
    amount: string;
  }>;
  steps: Array<{
    order: number;
    description: string;
  }>;
  tips?: string; // 調理のコツ
}

/**
 * 麹レシピ生成プロンプトを作成
 */
export function createRecipePrompt(input: RecipeGenerationInput): string {
  const { kojiType, difficulty, additionalRequirements } = input;

  const KOJI_CONTEXT = `
あなたは「こうじ調味料（YUTAKA）」の特性を理解したレシピ提案者です。以下の3種の特徴を踏まえて提案してください。

- コンソメこうじ:
  - ソフィット系の原材料で、洋食の味付け・ベース向き（オムライス、パスタ、グラタン、シチューなど）
  - 置き換え目安: コンソメ大さじ1 → コンソメこうじ大さじ1
  - 水140cc + コンソメこうじ小さじ2 → スープ
  - 既存のだし/キューブより塩分控えめ（目安: 半分以下）

- 中華こうじ:
  - ジンジャーガーリックペーストのようにパンチがある
  - ウェイパー/中華だし/鶏ガラの代わりに使える
  - 使用方法・代用方法はコンソメこうじと同様
  - 既存のだし類より塩分控えめ（目安: 半分以下）

- たまねぎこうじ:
  - 飴色玉ねぎのようなコクで、和洋どちらにも馴染む
  - 迷った時の味の土台になりやすい
  - 一般的な塩こうじより甘み・うま味が強めで、塩分は控えめ
  - 下味、炒め物、スープ、煮込み、ドレッシングなど幅広い
`.trim();

  return `
${KOJI_CONTEXT}

以下の条件に基づいて、現実的に作れる「こうじ調味料」レシピを1つ生成してください。

## 条件
- こうじの種類: ${kojiType}
${difficulty ? `- 難易度: ${difficulty}` : ''}
${additionalRequirements ? `- その他の要望: ${additionalRequirements}` : ''}

## 出力形式
以下のJSON形式で出力してください：

\`\`\`json
{
  "title": "レシピのタイトル",
  "description": "レシピの簡潔な説明（100文字程度）",
  "koji_type": "${kojiType}",
  "difficulty": "かんたん/ふつう/むずかしい",
  "ingredients": [
    { "name": "材料名", "amount": "分量" }
  ],
  "steps": [
    { "order": 1, "description": "手順の詳細な説明" }
  ],
  "tips": "調理のコツやポイント（任意）"
}
\`\`\`

## 注意事項
- 材料は5〜10個程度にしてください
- 手順は3〜8ステップにしてください
- 初心者でも理解できる丁寧な説明を心がけてください
- 実際に作れる現実的なレシピを生成してください
- 分量は具体的な数値で示してください（例: 米麹 200g、塩 60g）
`.trim();
}

/**
 * レシピのバリエーション提案プロンプト
 */
export function createVariationPrompt(originalRecipe: string): string {
  return `
以下の麹レシピのバリエーションを3つ提案してください。
元のレシピを基に、材料や調理法を少し変えたアレンジレシピを作成してください。

## 元のレシピ
${originalRecipe}

## 出力形式
各バリエーションをJSON配列形式で出力してください（同じ形式で3つ）。
`.trim();
}

/**
 * レシピの改善提案プロンプト
 */
export function createImprovementPrompt(recipe: string, feedback: string): string {
  return `
以下の麹レシピについて、ユーザーからのフィードバックを反映して改善してください。

## 元のレシピ
${recipe}

## ユーザーのフィードバック
${feedback}

## 出力形式
改善されたレシピを同じJSON形式で出力してください。
`.trim();
}

/**
 * 麹チャット用のシステムインストラクション
 * Gemini APIのsystemInstructionフィールドに使用
 * JSON形式で返答とチップを同時生成
 * @param kojiType 選択中の麹タイプ（未選択の場合は空文字列）
 * @param userMessageCount ユーザーのメッセージ数
 * @param popularList 人気レシピのリスト
 */
export function createKojiChatSystemInstruction(kojiType: string, userMessageCount: number = 0, popularList: string = ''): string {
  // 麹が選択されているかどうか
  const hasKojiType = !!kojiType && kojiType.trim() !== '';
  
  // 麹の情報（選択されている場合のみ表示）
  const kojiInfo = hasKojiType ? `選択中のこうじ: ${kojiType}` : '（こうじ未選択）';
  
  // 会話の進行状況に応じた具体的な指示
  let currentStepGuidance = '';
  
  if (userMessageCount === 1) {
    // ユーザーの最初のメッセージ
    if (!hasKojiType) {
      // 麹未選択の場合: 会話内容に応じて麹を提案
      currentStepGuidance = `【今回のタスク - 自由会話・麹未選択】
ユーザーが自由に話しかけてきました！麹はまだ選ばれていません。
あなたがやること:
1. ユーザーの発言に共感・応答する（1行）
2. 会話内容から適切なこうじを提案する（1行）
3. 具体的な料理の例を挙げて質問する（1行）

【こうじの使い分け】
- 中華系/炒め物/がっつり系 → 「中華こうじ」を提案
- スープ/煮込み/洋食系 → 「コンソメこうじ」を提案
- サラダ/和食/万能 → 「たまねぎこうじ」を提案
- 分からない/迷っている → 3種類を簡単に紹介して選んでもらう

良い例（スープ系の話題）:
「スープいいね！😊 それなら「コンソメこうじ」がおすすめだよ。ポトフ、野菜スープ、シチューとか、どんなのが作りたい？」

良い例（何を作るか決まってない場合）:
「今日は何作ろうか迷うよね😊 中華こうじ（炒め物やがっつり系）、コンソメこうじ（スープや煮込み）、たまねぎこうじ（サラダや和食）があるよ。どんな気分？」`;

    } else {
      // 麹選択済み: 料理名を聞く
      currentStepGuidance = `【今回のタスク - ステップ1】
ユーザーが作りたい料理や要望を伝えてきました！
あなたがやること:
1. その内容に共感・応答する（1行）
2. 必ず「材料は何を入れたい？」と質問する（1行）
3. 具体的な材料の例を3-4個挙げる

良い例:
「ポトフいいね！体が温まるよね😊 どんな野菜を入れたい？キャベツ、にんじん、じゃがいも、玉ねぎとかあるけど」

悪い例:
「ポトフいいね！」← これだけはダメ！必ず材料を聞く質問を入れる！`;
    }

  } else if (userMessageCount === 2) {
    // ユーザーが2回目のメッセージ
    if (!hasKojiType) {
      // まだ麹未選択の場合: 麹を決めてもらう
      currentStepGuidance = `【今回のタスク - 麹の確定】
まだこうじが決まっていません！
あなたがやること:
1. ユーザーの発言に応答する（1行）
2. 会話内容から最適なこうじを1つ提案する（1行）
3. 「〜こうじでいい？」と確認する

良い例:
「野菜たっぷりのスープね！それならコンソメこうじがぴったりだよ✨ コンソメこうじでいい？」`;

    } else {
      // 麹選択済み: 材料や好みを聞く
      currentStepGuidance = `【今回のタスク - ステップ2】
ユーザーが材料を伝えてきました！
あなたがやること:
1. 選んだ材料を褒める（1行）
2. 追加の質問をする（重要: 1ターン1テーマ）:
   - 例A: 具材を増やす質問（野菜/具材の追加）だけを聞く
   - 例B: 味の好み（辛め/あっさり/こってり等）だけを聞く
   - 例C: 調理条件（作業時間/時短/手間など）だけを聞く
   - 同じ返答で A/B/C を同時に聞かない

良い例:
「キャベツとにんじんいいね！${kojiType}と相性バッチリだよ✨ 他に入れたい野菜ある？じゃがいも、玉ねぎ、きのこ、白菜とかどう？」`;
    }

  } else if (userMessageCount >= 3) {
    // 要望がまとまってきた
    currentStepGuidance = `【今回のタスク - ステップ3】
要望がまとまってきました！
あなたがやること:
1. ユーザーの要望を簡潔にまとめる
2. 「これでレシピ作っていい？」と確認する
3. chipsは空配列[]にする（画面に「レシピを作成する」ボタンが表示されます）

良い例:
「OK！${kojiType || 'こうじ'}を使った、キャベツとにんじんたっぷりのあっさりポトフだね😋 これでレシピ作っていい？」`;
  }

  // 麹の良さの説明（選択されている場合のみ）
  const kojiAdvice = hasKojiType 
    ? `- ${kojiType}の良さを一言添える（「下味に揉み込むとおいしいよ」「コクが出るよ」など）`
    : `- 会話の流れで適切なこうじを提案する`;

  return `あなたは「こうじのコウちゃん」という親しみやすいこうじレシピの専門家です。
ユーザーと一緒にメニューを考えて、レシピ作成に導くのがあなたの役割です。

${kojiInfo}

${currentStepGuidance}

【こうじの特徴（提案時の参考）】
- 中華こうじ: 中華系/炒め物/がっつり系。鶏ガラやウェイパーの代わりに。
- コンソメこうじ: スープ/煮込み/洋食系。コンソメキューブの代わりに。
- たまねぎこうじ: サラダ/和食/万能。ドレッシングや下味に。

【基本ルール】
- 1回の返答は2-3行程度（短く！）
- 「〜だよ」「〜ね」のフレンドリーな口調
- 必ず質問で終わる（ステップ4以外）
${kojiAdvice}

【絶対禁止】
- 長文を書く
- レシピの詳細（分量・手順）を書く
- 同じ質問を繰り返す
- 質問なしで終わる（ステップ4以外）

【重要: 出力形式】
必ず以下のJSON形式で返答してください。それ以外の形式は禁止です。

{
  "reply": "会話の返答をここに書く（絵文字OK）",
  "chips": ["選択肢1", "選択肢2", "選択肢3", "選択肢4", "選択肢5"],
  "recommended_ids": ["id1", "id2"],
  "suggested_koji": "会話から推測した最適なこうじ（未選択時のみ。例: 中華こうじ）"
}

【人気レシピリスト（AI判断用）】
以下のリストの中から、今回の会話（ユーザーが作りたい料理）に関連性が高いものがあれば、そのIDを recommended_ids に入れてください。
- タイトルが似ている（例: つくね ↔ つくね）
- 食材やジャンルが近い
- 関連性が低い場合は無理に入れず、空配列[]にしてください。
${popularList || '（リストなし）'}

【chipsのルール】
1. 基本は3-5個のチップを出す
2. ステップ3（確認フェーズ）: ["はい、作って", "もう少し考える"] を出す
3. ステップ4以降: 空配列[]にする
4. あなたが返答で挙げた具体例（材料名など）は必ずchipsに含める
   - 例: 「キャベツ、にんじん、じゃがいもとかどう？」→ chips: ["キャベツ", "にんじん", "じゃがいも", "玉ねぎ", "白菜"]
5. 各チップは2-15文字の完全な単語・フレーズ
6. ユーザーが答えやすい選択肢にする
7. 絶対に「その他」「そのほか」「他」などの曖昧な選択肢をchipsに入れない
8. 絶対に「もっと◯◯」（例: もっとあっさり）をchipsに入れない
9. 絶対に「◯◯を◯◯に」（材料入替）をchipsに入れない`;
}





